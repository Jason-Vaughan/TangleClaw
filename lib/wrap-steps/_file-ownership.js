'use strict';

/**
 * Which uncommitted files a wrap may commit (#1406).
 *
 * The commit step used to run `git add -A`, which commits every uncommitted file
 * in the tree. The operator's own half-finished work, and a co-resident session's
 * work, went into a commit whose subject says "Session wrap", where nobody looks
 * for it. This module sorts the tree's uncommitted paths into three kinds:
 *
 * - **owned** — changed since this session launched, or written by the wrap
 *   itself to a file that was not already uncommitted at launch. Committed
 *   without asking.
 * - **foreign** — already uncommitted when the session launched, or not provably
 *   this session's. Committed only when the operator says `include`, and left
 *   uncommitted when they say `leave`. A foreign path with no decision blocks the
 *   wrap until the operator decides; see the `session-files` step.
 *
 * **How "since launch" is judged.** When the session's launch baseline has a
 * complete dirty set for this same tree, a path is foreign exactly when it was in
 * that set. Otherwise (a worktree the session moved into, a session launched
 * before baselines existed, or a dirty set too large to record in full) a path is
 * owned when its modification time is at or after the session's start. A
 * deletion has no file time to read, so without a snapshot it is foreign.
 *
 * **TangleClaw's own paths are judged first** (#1508, #1509), by
 * `_tc-owned-paths.js`, and never reach the rules above: machine state is
 * neither committed nor asked about, and a tracked file whose change is provably
 * TangleClaw's is committed as maintenance. Without this, one TangleClaw write
 * that missed a commit made its file "already uncommitted at launch" in every
 * later session, and the wrap asked about it on every wrap.
 *
 * Known limit: a co-resident session's edit made AFTER this session launched
 * looks like this session's change. The drawer says "changed since this session
 * launched", never "yours", for that reason.
 */

const fs = require('node:fs');
const path = require('node:path');
const tcOwned = require('./_tc-owned-paths');

/** Why a path is foreign, in words the drawer shows the operator. */
const FOREIGN_REASONS = Object.freeze({
  'dirty-at-launch': 'already uncommitted when this session launched',
  'predates-launch': 'last changed before this session launched',
  'unknown-deletion': 'deleted, and there is no launch record to show when',
  'unknown-start': 'no record of when this session started',
  'unreadable-time': 'its change time could not be read',
  // #1619. Distinct from the rest: every other reason says "this file may not
  // be the session's", and the operator decides on that basis. This one says
  // TangleClaw looked at its own block and found a value that must not be
  // committed — a project name, a machine origin or a live token. Without it
  // the refusal changed nothing: the carrier fell through to the mtime rule,
  // and one regenerated by the running server mid-session carries this
  // session's mtime, so it landed in `owned` and was staged exactly as
  // maintenance would have been.
  'carries-identity': 'TangleClaw\'s own block in it carries a value that must not be committed'
});

/** The two decisions an operator can make about a foreign path. */
const DECISIONS = Object.freeze({ INCLUDE: 'include', LEAVE: 'leave' });

/**
 * The argv that lists uncommitted paths the way the launch baseline recorded
 * them: repo-root-relative, every untracked file listed on its own.
 *
 * @returns {string[]} Argv after `git`.
 */
function statusArgs() {
  return ['status', '--porcelain', '-z', '--untracked-files=all'];
}

/**
 * Parse porcelain `-z` output into entries that remember whether the path is gone.
 *
 * Two fields beyond the path exist for different questions and must not be
 * conflated. `deleted` means "this path is not in the working tree", which is
 * what ownership cares about. `indexRemoved` means "git has ALREADY removed it
 * from the index", which is what staging cares about — a rename source and a
 * staged deletion match no pathspec `git add` can resolve, and feeding one back
 * to `git add` exits 128 and blocks the wrap (#1629). An UNSTAGED deletion is
 * `deleted` but not `indexRemoved`: it is still in the index, `git add` stages
 * its removal, and excluding it would stop the wrap committing ordinary file
 * deletions. Measured against real git, not inferred.
 *
 * `renamePair` links the two halves of one rename with a shared id, so a caller
 * can see that authorizing one half without the other turns a rename into an
 * add or a delete.
 *
 * @param {string} stdout - Raw `-z` output.
 * @returns {Array<{path:string, deleted:boolean, indexRemoved:boolean, renamePair:(number|null)}>}
 *   One entry per path; a rename contributes its new name and its old name (the
 *   old one deleted), both carrying the same `renamePair`.
 */
function parseStatus(stdout) {
  const fields = String(stdout || '').split('\0');
  const out = [];
  const seen = new Set();
  let pairSeq = 0;
  const add = (p, deleted, indexRemoved, renamePair) => {
    if (!p || seen.has(p)) return;
    seen.add(p);
    out.push({ path: p, deleted, indexRemoved, renamePair });
  };
  for (let i = 0; i < fields.length; i += 1) {
    const entry = fields[i];
    if (entry.length < 4) continue;
    const xy = entry.slice(0, 2);
    const isRenameOrCopy = xy[0] === 'R' || xy[0] === 'C';
    // ONLY a rename pairs. A copy's source is not going anywhere — it stays
    // tracked, unchanged and addable — so committing the copy without it is an
    // ordinary add, not half a move. Pairing copies too would block a wrap on a
    // repo configured with `status.renames=copies` for a change nobody split.
    const pair = xy[0] === 'R' ? (pairSeq += 1) : null;
    // The DESTINATION is present on disk and in the index, whatever X says.
    add(entry.slice(3), xy.includes('D'), xy[0] === 'D', pair);
    if (isRenameOrCopy) {
      i += 1;
      add(fields[i], xy[0] === 'R', xy[0] === 'R', pair);
    }
  }
  return out;
}

/**
 * Sort uncommitted paths into owned and foreign, and apply the operator's decisions.
 *
 * @param {object} scope - The wrap run's scope (`lib/wrap-scope.js`): reads
 *   `snapshotApplies`, `baseline.dirty.paths`, `startedAtMs`, `workToplevel`.
 * @param {Array<{path:string, deleted:boolean}>} dirty - From {@link parseStatus}.
 * @param {object} [options]
 * @param {Iterable<string>} [options.wrapWritten] - Repo-root-relative paths the
 *   wrap itself wrote this run. Owned unless the launch snapshot shows the file
 *   was already uncommitted, which the operator decides.
 * @param {Object<string, string>} [options.decisions] - `{[path]: 'include'|'leave'}`.
 *   Only entries for paths this classification calls foreign are honored.
 * @param {(abs: string) => number|null} [options.mtimeMs] - Test seam.
 * @returns {{owned:string[], foreign:Array<{path:string, reason:string, why:string, deleted:boolean}>,
 *   included:string[], left:string[], undecided:Array<{path:string, reason:string, why:string, deleted:boolean}>,
 *   tangleclawMaintenance:string[], tangleclawState:string[], stageable:string[], addable:string[],
 *   splitRenames:Array<{pair:number, staged:string[], left:string[], reason:string}>,
 *   indexRemoved:string[], renamePairs:Array<{pair:number, paths:string[]}>}}
 *   `stageable` is `owned`, `included` and `tangleclawMaintenance` — exactly what
 *   the commit may stage. `addable` is the subset `git add` can resolve (#1629).
 *   `splitRenames` names renames whose halves got different answers.
 *   `indexRemoved` and `renamePairs` are the raw git facts a rebuild needs, so
 *   `reclassify` never has to re-read `dirty`. `tangleclawState` is never staged.
 */
function classify(scope, dirty, options = {}) {
  const wrapWritten = new Set(options.wrapWritten || []);
  const decisions = options.decisions && typeof options.decisions === 'object' ? options.decisions : {};
  const mtimeMs = options.mtimeMs || _mtimeMs;
  const launchDirty = scope && scope.snapshotApplies && scope.baseline && scope.baseline.dirty
    ? new Set(scope.baseline.dirty.paths)
    : null;
  const startedAtMs = scope && Number.isFinite(scope.startedAtMs) ? scope.startedAtMs : null;
  const root = scope && scope.workToplevel ? scope.workToplevel : null;

  const tcVerdicts = tcOwned.judge(root, dirty);
  // Carried on the verdict map rather than re-derived: only `judge` has read
  // both copies of the carrier (#1619).
  const identityRefusals = tcVerdicts.identityRefusals;
  const tangleclawMaintenance = [];
  const tangleclawState = [];
  const owned = [];
  const foreign = [];
  for (const entry of dirty) {
    const p = entry.path;
    const tcKind = tcVerdicts.get(p);
    if (tcKind === tcOwned.KINDS.STATE) { tangleclawState.push(p); continue; }
    if (tcKind === tcOwned.KINDS.MAINTENANCE) { tangleclawMaintenance.push(p); continue; }
    // Asked about, never staged by default — the one "not ours" that carries a
    // positive finding rather than an absence of proof (#1619).
    if (identityRefusals && identityRefusals.has(p)) {
      foreign.push({ path: p, reason: 'carries-identity', why: FOREIGN_REASONS['carries-identity'], deleted: entry.deleted });
      continue;
    }
    let reason = null;
    if (launchDirty) {
      // Checked BEFORE the wrap's own writes. A file that already held someone's
      // uncommitted edits stays theirs to decide even when a wrap step then
      // rewrites it (version-bump on CHANGELOG.md, features-toc on FEATURES.md):
      // committing it would commit those edits too, which is the sweep this
      // module exists to stop. A Leave therefore also leaves the wrap's change.
      if (launchDirty.has(p)) reason = 'dirty-at-launch';
    } else if (wrapWritten.has(p)) {
      // With no snapshot, the file time of a file the wrap just wrote is the
      // wrap's own, so it says nothing about who changed it before. It is the
      // session's — unless the operator was already asked about it (it predated
      // the session when `session-files` read the tree) and answered. An answer
      // wins: a Left file stays out even after a wrap step rewrites it.
      reason = Object.prototype.hasOwnProperty.call(decisions, p) ? 'predates-launch' : null;
    } else if (entry.deleted) {
      reason = 'unknown-deletion';
    } else if (startedAtMs === null || !root) {
      reason = 'unknown-start';
    } else {
      const m = mtimeMs(path.join(root, p));
      // SQLite records the start to the second, rounded down, so a file written in
      // the launch's own second counts as this session's — the launch itself
      // writes files in that second.
      if (m === null) reason = 'unreadable-time';
      else if (m < startedAtMs) reason = 'predates-launch';
    }
    if (reason) {
      foreign.push({ path: p, reason, why: FOREIGN_REASONS[reason], deleted: entry.deleted });
    } else {
      owned.push(p);
    }
  }

  const included = [];
  const left = [];
  const undecided = [];
  for (const f of foreign) {
    const d = Object.prototype.hasOwnProperty.call(decisions, f.path) ? decisions[f.path] : null;
    if (d === DECISIONS.INCLUDE) included.push(f.path);
    else if (d === DECISIONS.LEAVE) left.push(f.path);
    else undecided.push(f);
  }
  return {
    owned,
    foreign,
    included,
    left,
    undecided,
    tangleclawMaintenance,
    tangleclawState,
    // The two raw git facts a rebuild needs, carried on the classification so
    // it never has to re-read `dirty` — `./_secret-check` filters buckets and
    // rebuilds from what it holds.
    indexRemoved: (dirty || []).filter((f) => f.indexRemoved).map((f) => f.path),
    renamePairs: renamePairsOf(dirty),
    ...selectionOf({ owned, included, tangleclawMaintenance }, dirty)
  };
}

/**
 * The three selections that must always be rebuilt together.
 *
 * `stageable`, `addable` and `splitRenames` are one answer in three shapes: what
 * may be committed, what `git add` can be handed, and which renames were split
 * by that answer. A caller that filtered buckets and rebuilt only `stageable`
 * would leave the other two describing the selection it just replaced — and
 * nothing would fail, which is exactly how #1513 lost a bucket from every wrap
 * commit. One function, so there is no way to rebuild one without the rest.
 *
 * @param {{owned: string[], included: string[], tangleclawMaintenance: string[]}} buckets
 * @param {Array<{path:string, indexRemoved?:boolean, renamePair?:(number|null)}>} dirty -
 *   From {@link parseStatus}, or a classification's own `indexRemoved`/`renamePairs`
 *   rebuilt into the same shape.
 * @returns {{stageable:string[], addable:string[], splitRenames:Array<object>}}
 */
function selectionOf(buckets, dirty) {
  const stageable = stageableOf(buckets);
  return {
    stageable,
    addable: addableOf(stageable, dirty),
    splitRenames: splitRenamesOf(dirty, stageable, buckets)
  };
}

/**
 * Rebuild every selection after a caller has filtered the buckets.
 *
 * The supported way to narrow a classification: it reassembles `dirty` from the
 * facts the classification carries, so a caller needs neither the original git
 * output nor knowledge of which selections exist.
 *
 * @param {object} classified - A classification from {@link classify}.
 * @param {{owned: string[], included: string[], tangleclawMaintenance: string[]}} buckets -
 *   The narrowed buckets.
 * @returns {object} A new classification with all three selections consistent.
 */
function reclassify(classified, buckets) {
  const removed = new Set(classified.indexRemoved || []);
  const dirty = [];
  for (const pair of classified.renamePairs || []) {
    for (const path of pair.paths) {
      dirty.push({ path, indexRemoved: removed.has(path), renamePair: pair.pair });
    }
  }
  for (const path of removed) {
    if (!dirty.some((f) => f.path === path)) dirty.push({ path, indexRemoved: true, renamePair: null });
  }
  return { ...classified, ...buckets, ...selectionOf(buckets, dirty) };
}

/**
 * The authorized paths git has already removed from the index.
 *
 * The temporary-index commit path needs these by name: that index is seeded
 * from HEAD, where a rename's source still exists, so it has to be removed
 * there too or the commit keeps the source beside its destination. Derived here
 * rather than filtered at the call site, so "which authorized paths are already
 * removed" has one definition (#1629).
 *
 * @param {object} classified - A classification from {@link classify}.
 * @returns {string[]}
 */
function removedFromIndexOf(classified) {
  const removed = new Set(classified.indexRemoved);
  return classified.stageable.filter((p) => removed.has(p));
}

/**
 * Every rename in the tree, as pairs of path names.
 *
 * @param {Array<{path:string, renamePair:(number|null)}>} dirty - From {@link parseStatus}.
 * @returns {Array<{pair:number, paths:string[]}>}
 */
function renamePairsOf(dirty) {
  const pairs = new Map();
  for (const f of dirty || []) {
    if (f.renamePair == null) continue;
    if (!pairs.has(f.renamePair)) pairs.set(f.renamePair, { pair: f.renamePair, paths: [] });
    pairs.get(f.renamePair).paths.push(f.path);
  }
  return [...pairs.values()];
}

/**
 * Which buckets of a classification may be staged, in commit order.
 *
 * The one definition of "what the wrap may commit", and one INPUT to a
 * classification's selections rather than the whole answer.
 *
 * **Rebuilding a filtered classification goes through `reclassify`, not here**
 * (#1629). `stageable` now has two derived siblings — `addable` and
 * `splitRenames` — and calling this alone rebuilds one of the three, leaving
 * the other two describing the selection that was just replaced. Nothing fails
 * when that happens, which is the #1513 shape in a new place.
 *
 * @param {{owned: string[], included: string[], tangleclawMaintenance: string[]}} buckets
 * @returns {string[]}
 */
function stageableOf(buckets) {
  return [...buckets.owned, ...buckets.included, ...buckets.tangleclawMaintenance];
}

/**
 * Which of the authorized paths `git add` may actually be handed.
 *
 * `stageable` is the COMMIT selection — everything this wrap is allowed to
 * publish. `addable` is the subset `git add` can resolve. They differ for paths
 * git has already removed from the index (a rename's source, a staged deletion):
 * those belong in the commit, and handing one to `git add` exits 128 and blocks
 * the wrap (#1629).
 *
 * A path absent from `dirty` is kept rather than dropped: the caller owns the
 * selection, and silently shrinking it here would be a second place deciding
 * what gets committed.
 *
 * @param {string[]} stageable - From {@link stageableOf}.
 * @param {Array<{path:string, indexRemoved?:boolean}>} dirty - From {@link parseStatus}.
 * @returns {string[]}
 */
function addableOf(stageable, dirty) {
  const removed = new Set((dirty || []).filter((f) => f.indexRemoved).map((f) => f.path));
  return stageable.filter((p) => !removed.has(p));
}

/**
 * Renames whose two halves did not get the same answer.
 *
 * Committing one half of a rename is not a smaller version of committing it —
 * it is a different change. Publish only the destination and the source stays
 * tracked, so the commit reads as an add and the file exists twice; publish only
 * the source and it reads as a deletion of work that was moved, not removed.
 * Neither is what anyone chose, and both look like a successful wrap.
 *
 * So the pair is reported and the commit step refuses, rather than this function
 * quietly promoting the left half — an operator who said "leave" about a path
 * must not have it committed because of what its other half was called.
 *
 * @param {Array<{path:string, renamePair:(number|null)}>} dirty - From {@link parseStatus}.
 * @param {string[]} stageable - The authorized commit selection.
 * @returns {Array<{pair:number, staged:string[], left:string[]}>} One entry per split rename.
 */
function splitRenamesOf(dirty, stageable, buckets = null) {
  const authorized = new Set(stageable);
  const decidable = buckets
    ? new Set([...(buckets.left || []), ...(buckets.undecided || []).map((f) => f.path || f)])
    : null;
  const pairs = new Map();
  for (const f of dirty || []) {
    if (f.renamePair == null) continue;
    if (!pairs.has(f.renamePair)) pairs.set(f.renamePair, { pair: f.renamePair, staged: [], left: [] });
    pairs.get(f.renamePair)[authorized.has(f.path) ? 'staged' : 'left'].push(f.path);
  }
  return [...pairs.values()]
    .filter((p) => p.staged.length > 0 && p.left.length > 0)
    .map((p) => ({
      ...p,
      // Why the other half is out, because it decides what advice is possible.
      // `decision` means the operator chose Leave, or has not chosen yet, and
      // can choose again. Anything else — withheld by the secret scan, or
      // TangleClaw state a wrap never commits — is not theirs to reverse, and
      // "include both" would send them looking for a control that is not there.
      // With no buckets to consult, the honest answer is `unknown`, never the
      // assumption that they can fix it.
      reason: decidable === null ? 'unknown' : (p.left.every((path) => decidable.has(path)) ? 'decision' : 'not-committable')
    }));
}

/**
 * A file's modification time, or null when it cannot be read.
 *
 * @param {string} abs - Absolute path.
 * @returns {number|null}
 */
function _mtimeMs(abs) {
  try {
    return fs.lstatSync(abs).mtimeMs;
  } catch {
    return null;
  }
}

/**
 * The one-line blocker for paths awaiting a decision.
 *
 * @param {Array<{path:string}>} undecided - From {@link classify}.
 * @returns {string}
 */
function blockerLine(undecided) {
  const n = undecided.length;
  return `${n} uncommitted file${n === 1 ? '' : 's'} ${n === 1 ? 'was' : 'were'} not changed by this session — choose Include or Leave for each before the wrap commits`;
}

/**
 * The remediation text for paths awaiting a decision, naming each and why.
 *
 * @param {Array<{path:string, why:string}>} undecided - From {@link classify}.
 * @returns {string}
 */
function remediation(undecided) {
  const listed = undecided.map((f) => `  - ${f.path} (${f.why})`).join('\n');
  return 'These files have uncommitted changes that this session did not make, so the wrap will not commit them without asking:\n'
    + `${listed}\n`
    + 'Choose Include to commit a file in this wrap, or Leave to keep it uncommitted where it is, then Retry. '
    + 'Leave never discards anything. A file you leave stays out of the commit even if a wrap step also changes it (for example the changelog or the Feature Index), and that change stays uncommitted with it. '
    + 'If another session is still working on a file, leave it.';
}

/**
 * Keep only well-formed decisions from an options bag that arrived over HTTP.
 *
 * @param {*} raw - `options.pathDecisions` as received.
 * @returns {Object<string, string>} `{[path]: 'include'|'leave'}`.
 */
function sanitizeDecisions(raw) {
  const out = {};
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return out;
  for (const [p, d] of Object.entries(raw)) {
    if (typeof p === 'string' && p && (d === DECISIONS.INCLUDE || d === DECISIONS.LEAVE)) out[p] = d;
  }
  return out;
}

