'use strict';

/**
 * Which uncommitted paths in a managed project are TangleClaw's own (#1508, #1509).
 *
 * TangleClaw writes into the project it manages: machine state under
 * `.tangleclaw/`, a delimited block inside the engine's config file, hook
 * entries it retires from a shared settings file, keys it fills into
 * `project.json`. When one of those writes misses a commit, the file is
 * "already uncommitted at launch" in every later session, and the wrap's
 * ownership check asks the operator about it on every wrap. This module is the
 * one place that says what TangleClaw owns, so that question stops.
 *
 * It answers per path, with three outcomes:
 *
 * - **state** — machine state TangleClaw rewrites routinely. Never committed
 *   and never asked about. Committing it would turn every wrap into churn and
 *   can put session transcripts and uploads into project history.
 * - **maintenance** — a tracked file whose change is PROVABLY TangleClaw's,
 *   established by comparing the committed copy with the working copy. Committed
 *   without asking, and named in the wrap's output.
 * - **null** — anything else, including every failure to read or parse. The
 *   path is judged exactly as it was before this module existed, which for a
 *   file already uncommitted at launch means the operator is asked. That is the
 *   safe answer: a wrong "maintenance" commits someone's edit under a claim that
 *   TangleClaw made it.
 *
 * What never counts as proof: a `Generated by TangleClaw` header. It shows
 * TangleClaw generated the file once, not that the current change is
 * TangleClaw's, so whole-file generated configs are always judged as usual.
 */

const path = require('node:path');
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const { createLogger } = require('../logger');
const managedBlock = require('../managed-block');

const log = createLogger('wrap-tc-owned-paths');

/** The two ownership kinds this module can return. */
const KINDS = Object.freeze({ STATE: 'state', MAINTENANCE: 'maintenance' });

/**
 * Machine state TangleClaw rewrites as it runs: one entry per writer, each with a
 * matcher for a repo-root-relative path and the gitignore patterns that describe
 * the same paths (for the local exclude written at launch).
 *
 * Deliberately a list of named files, not the `.tangleclaw/` directory: plans,
 * priming prompts and memories live there too, and those are authored content
 * a wrap must commit.
 *
 * Each name is read from the module that writes the file, so a rename at the
 * writer moves the matcher and the pattern with it rather than bringing the
 * question back. Built on first use; a writer that fails to load contributes
 * nothing, which means its file is asked about — never committed by mistake —
 * and is not excluded.
 *
 * @returns {Array<{label:string, match:(p: string) => boolean, patterns:string[]}>}
 */
function _stateEntries() {
  if (_stateEntries.cache) return _stateEntries.cache;
  const entries = [];
  const add = (label, build) => {
    try {
      entries.push({ label, ...build() });
    } catch (err) {
      // prawduct:allow prawduct/broad-except -- a writer module failing to load
      // must cost its file's matcher (the operator is asked), not the wrap.
      log.info('TangleClaw state matcher unavailable; that file will be asked about', { label, error: err && err.message });
    }
  };
  const escape = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  // A gitignore pattern anchored at the repository root, matching one literal name.
  const literal = (rel) => `/${rel.replace(/[*?[\]\\!#]/g, '\\$&')}`;
  add('project files', () => {
    const files = require('../tangleclaw-project-files');
    const exact = [files.SESSION_PRIME_RELPATH, files.UI_WRAP_ADVISORY_RELPATH, files.MEDUSA_REGISTRY_RELPATH, files.WRAP_STATE_RELPATH];
    const set = new Set(exact);
    return { match: (p) => set.has(p), patterns: exact.map(literal) };
  });
  add('session rule shards', () => {
    const { SHARD_STEM, RECEIPT_STEM } = require('../session-rules-channel');
    const shard = new RegExp(`^\\.tangleclaw/${escape(SHARD_STEM)}-\\d+\\.json$`);
    const receipt = `.tangleclaw/${RECEIPT_STEM}.json`;
    return {
      match: (p) => shard.test(p) || p === receipt,
      // The shard glob is wider than the matcher (`-*` vs `-<digits>`): it also
      // covers the receipt, which shares the stem, and nothing else TangleClaw writes.
      patterns: [`${literal(`.tangleclaw/${SHARD_STEM}`)}-*.json`, literal(receipt)]
    };
  });
  add('version cache', () => {
    const { VERSION_CACHE_FILENAME, STAGING_PREFIX } = require('../project-version-files');
    const cache = `.tangleclaw/${VERSION_CACHE_FILENAME}`;
    const staging = `.tangleclaw/${STAGING_PREFIX}`;
    return {
      match: (p) => p === cache || p.startsWith(staging),
      patterns: [literal(cache), `${literal(staging)}*`]
    };
  });
  add('critic runs', () => {
    const { CRITIC_RUNS_RELPATH } = require('../actions/invoke-critic');
    const rel = CRITIC_RUNS_RELPATH.split(path.sep).join('/');
    return { match: (p) => p === rel, patterns: [literal(rel)] };
  });
  add('continuity store', () => {
    const dir = require('../continuity').storeDir('');
    const rel = dir.split(path.sep).join('/');
    const prefix = `${rel}/`;
    return { match: (p) => p.startsWith(prefix), patterns: [`${literal(rel)}/`] };
  });
  add('handoff store', () => {
    // `.tangleclaw/handoff/` — the per-attempt handoff documents (Train 21,
    // #1585). TangleClaw-owned state like the continuity store beside it: the
    // wrap writes it, it is gitignored, and it must never be offered to the
    // operator as an uncommitted file they have to decide about.
    const rel = '.tangleclaw/handoff';
    const prefix = `${rel}/`;
    return { match: (p) => p === rel || p.startsWith(prefix), patterns: [`${literal(rel)}/`] };
  });
  add('wrap content captures', () => {
    // The files AI content steps write for the wrap to read back and then delete.
    const captures = [...new Set(require('../wrap-default-pipeline').steps()
      .map((st) => st && st.captureFile)
      .filter((f) => typeof f === 'string' && f.startsWith('.tangleclaw/')))];
    const set = new Set(captures);
    return { match: (p) => set.has(p), patterns: captures.map(literal) };
  });
  _stateEntries.cache = entries;
  return entries;
}

/**
 * The state matchers alone.
 *
 * @returns {Array<(p: string) => boolean>}
 */
function _statePathMatchers() {
  return _stateEntries().map((e) => e.match);
}

/**
 * Gitignore patterns (anchored at the repository root) for every state path, in
 * registry order, for the local exclude TangleClaw writes at launch.
 *
 * @returns {string[]}
 */
function statePatterns() {
  return _stateEntries().flatMap((e) => e.patterns);
}

/** Where TangleClaw keeps per-project config. */
const PROJECT_CONFIG_PATH = '.tangleclaw/project.json';

/**
 * A project.json key TangleClaw moved out of the file (to `.tangleclaw/state.json`).
 * Its removal is TangleClaw's migration. A value changed between two recorded
 * boundaries is the stamp an earlier TangleClaw left before the move — still
 * state, so a project upgraded mid-flight is not asked about it. Adding the key
 * is neither: no writer, old or new, does that to a file that lacked it.
 */
const RETIRED_CONFIG_KEYS = Object.freeze(['lastWrapSha']);

/** Keys only TangleClaw's own one-shot migrations write. */
const MIGRATION_CONFIG_KEYS = Object.freeze(['wrapOverridesSeeded']);

/**
 * Whether a path is TangleClaw machine state.
 *
 * @param {string} relPath - Repo-root-relative path, forward slashes.
 * @returns {boolean}
 */
function isStatePath(relPath) {
  return _statePathMatchers().some((match) => match(relPath));
}

/**
 * The files TangleClaw may splice a managed block into, with the comment syntax
 * that locates the markers in each.
 *
 * Derived from every engine profile rather than from the project's current
 * engine: a project that switched engines still carries the old engine's file,
 * and the proof below is what keeps a broad candidate list safe — an operator
 * edit outside the markers can never pass it.
 *
 * @param {object[]} profiles - Engine profiles (`configFormat.{filename,syntax}`).
 * @param {string[]} sharedCarriers - Convention files every engine reads.
 * @returns {Map<string, string>} Filename → syntax.
 */
function carrierFiles(profiles, sharedCarriers) {
  const out = new Map();
  for (const p of profiles || []) {
    const fmt = p && p.configFormat;
    if (fmt && typeof fmt.filename === 'string' && typeof fmt.syntax === 'string') {
      out.set(fmt.filename, fmt.syntax);
    }
  }
  for (const f of sharedCarriers || []) {
    if (!out.has(f)) out.set(f, 'markdown');
  }
  return out;
}

/**
 * Structural equality for JSON values.
 *
 * @param {*} a
 * @param {*} b
 * @returns {boolean}
 */
function _jsonEqual(a, b) {
  return JSON.stringify(_sorted(a)) === JSON.stringify(_sorted(b));
}

/**
 * A copy of a JSON value with object keys sorted, so key order never decides equality.
 *
 * @param {*} v
 * @returns {*}
 */
function _sorted(v) {
  if (Array.isArray(v)) return v.map(_sorted);
  if (v && typeof v === 'object') {
    const out = {};
    for (const k of Object.keys(v).sort()) out[k] = _sorted(v[k]);
    return out;
  }
  return v;
}

/**
 * Parse text as a JSON object, or null.
 *
 * @param {string|null} text
 * @returns {object|null}
 */
function _parseObject(text) {
  if (typeof text !== 'string') return null;
  try {
    const v = JSON.parse(text);
    return v && typeof v === 'object' && !Array.isArray(v) ? v : null;
  } catch {
    return null;
  }
}

/**
 * Judge a `project.json` change.
 *
 * @param {string} head - Committed text.
 * @param {string} work - Working text.
 * @param {object} defaults - `DEFAULT_PROJECT_CONFIG`.
 * @returns {{kind: (string|null), reason: string}}
 */
function judgeProjectConfig(head, work, defaults) {
  const before = _parseObject(head);
  const after = _parseObject(work);
  if (!before || !after) return { kind: null, reason: 'project.json is not a JSON object on both sides' };
  const changed = [...new Set([...Object.keys(before), ...Object.keys(after)])]
    .filter((k) => !_jsonEqual(before[k], after[k]));
  if (changed.length === 0) return { kind: KINDS.MAINTENANCE, reason: 'project.json was only re-serialised' };
  const has = (o, k) => Object.prototype.hasOwnProperty.call(o, k);
  if (changed.every((k) => RETIRED_CONFIG_KEYS.includes(k) && has(before, k) && has(after, k))) {
    return { kind: KINDS.STATE, reason: 'only the retired wrap boundary stamp changed' };
  }
  const foreign = changed.filter((k) => {
    if (MIGRATION_CONFIG_KEYS.includes(k)) return false;
    if (RETIRED_CONFIG_KEYS.includes(k)) return Object.prototype.hasOwnProperty.call(after, k);
    // The legacy engine id rename is a load-time migration that lands on the next save.
    if (k === 'engine' && before[k] === 'claude-code' && after[k] === 'claude') return false;
    // A save writes every default key the file lacked; a key the committed copy
    // did not have, holding exactly its default, is that fill-in and nothing more.
    if (!Object.prototype.hasOwnProperty.call(before, k)
      && Object.prototype.hasOwnProperty.call(after, k)
      && defaults && Object.prototype.hasOwnProperty.call(defaults, k)
      && _jsonEqual(after[k], defaults[k])) return false;
    return true;
  });
  if (foreign.length > 0) {
    return { kind: null, reason: `project.json keys changed that TangleClaw does not own on its own: ${foreign.join(', ')}` };
  }
  return { kind: KINDS.MAINTENANCE, reason: `project.json changed only in keys TangleClaw maintains (${changed.join(', ')})` };
}

/**
 * Whether `after` is `before` with some TangleClaw hook entries removed, and
 * nothing else changed.
 *
 * Removal is the only change TangleClaw makes to the shared settings file: it
 * retires its own hooks from there and installs them in the machine-local file.
 * So anything else is refused — an entry added, even one pointing at a TangleClaw
 * script; an entry edited, even one TangleClaw once wrote; a reordering. Those
 * run for everyone who clones the repository, and they are not TangleClaw's to
 * commit.
 *
 * @param {object} before - Committed settings.
 * @param {object} after - Working settings.
 * @param {(entry: object) => boolean} isTcHook
 * @returns {boolean}
 */
function _onlyTcHooksRemoved(before, after, isTcHook) {
  const { hooks: beforeHooks, ...beforeRest } = before;
  const { hooks: afterHooks, ...afterRest } = after;
  if (!_jsonEqual(beforeRest, afterRest)) return false;
  const bh = beforeHooks === undefined ? {} : beforeHooks;
  const ah = afterHooks === undefined ? {} : afterHooks;
  if (!bh || typeof bh !== 'object' || Array.isArray(bh)) return _jsonEqual(beforeHooks, afterHooks);
  if (!ah || typeof ah !== 'object' || Array.isArray(ah)) return false;
  for (const event of Object.keys(ah)) {
    if (!Object.prototype.hasOwnProperty.call(bh, event)) return false;
  }
  for (const [event, entries] of Object.entries(bh)) {
    const kept = Object.prototype.hasOwnProperty.call(ah, event) ? ah[event] : [];
    if (!Array.isArray(entries) || !Array.isArray(kept)) {
      if (!_jsonEqual(entries, ah[event])) return false;
      continue;
    }
    let j = 0;
    for (const entry of entries) {
      if (j < kept.length && _jsonEqual(entry, kept[j])) j += 1;
      else if (!isTcHook(entry)) return false;
    }
    if (j !== kept.length) return false;
    // An event left empty is removed by the writer, never kept as `[]`.
    if (Object.prototype.hasOwnProperty.call(ah, event) && kept.length === 0 && entries.length > 0) return false;
  }
  // The writer drops a `hooks` object that retirement emptied; one kept as `{}` was not its write.
  if (afterHooks !== undefined && beforeHooks !== undefined && Object.keys(ah).length === 0 && Object.keys(bh).length > 0) return false;
  if (afterHooks !== undefined && beforeHooks === undefined) return false;
  return true;
}

/**
 * Judge a shared hook settings file change.
 *
 * @param {string} head
 * @param {string} work
 * @param {(entry: object) => boolean} isTcHook
 * @returns {{kind: (string|null), reason: string}}
 */
function judgeHookSettings(head, work, isTcHook) {
  const before = _parseObject(head);
  const after = _parseObject(work);
  if (!before || !after) return { kind: null, reason: 'settings file is not a JSON object on both sides' };
  if (!_onlyTcHooksRemoved(before, after, isTcHook)) {
    return { kind: null, reason: 'the settings file changed in some way other than TangleClaw removing its own hook entries' };
  }
  return { kind: KINDS.MAINTENANCE, reason: 'only TangleClaw\'s hook entries were removed' };
}

/** The engine profiles that ship with this install. */
const BUNDLED_ENGINES_DIR = path.join(__dirname, '..', '..', 'data', 'engines');

/**
 * Read the bundled engine profiles.
 *
 * The bundled set rather than the store's profile directory: the store's copy is
 * synced from these files at boot, and reading it here would make every wrap test
 * read the live install's state. A profile an operator adds by hand to the store
 * directory is therefore not a known carrier, which costs only the question this
 * module exists to remove — never a wrong commit.
 *
 * @returns {object[]}
 */
function _bundledProfiles() {
  return fs.readdirSync(BUNDLED_ENGINES_DIR).filter((f) => f.endsWith('.json'))
    .map((f) => JSON.parse(fs.readFileSync(path.join(BUNDLED_ENGINES_DIR, f), 'utf8')));
}

/**
 * Seams, so tests drive every branch against a real repository or a stub.
 * Engine knowledge is read lazily: the engine layer is heavy to load, and a
 * failure to load it must cost a declined judgement, never the wrap.
 */
const _internal = {
  gitShowHead: (root, relPath) => execFileSync('git', ['show', `HEAD:${relPath}`], {
    cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], timeout: 10000, maxBuffer: 16 * 1024 * 1024
  }),
  readWork: (root, relPath) => fs.readFileSync(path.join(root, relPath), 'utf8'),
  engineKnowledge: () => {
    const engines = require('../engines');
    const { DEFAULT_PROJECT_CONFIG } = require('../project-config');
    return {
      carriers: carrierFiles(_bundledProfiles(), engines.SHARED_CONVENTION_CARRIERS),
      markersFor: (syntax) => engines.managedBlockMarkers(syntax),
      isTcHook: engines.isTangleClawHookEntry,
      hookSettingsPaths: engines.SHARED_HOOK_SETTINGS_PATHS,
      projectDefaults: DEFAULT_PROJECT_CONFIG
    };
  }
};

/**
 * Judge every dirty entry in one pass.
 *
 * @param {string|null} root - The work tree's toplevel. Without one nothing can
 *   be read, so only the name-based state registry applies.
 * @param {Array<{path:string, deleted:boolean}>} dirty - Parsed `git status`.
 * @returns {Map<string, string>} Path → `state` | `maintenance`, for owned paths only.
 */
function judge(root, dirty) {
  const out = new Map();
  // Carriers refused for carrying identity, path → why. Exposed on the result
  // so the ownership rules can route them to the operator instead of letting
  // them fall through to the generic mtime test (#1619).
  const identityRefusals = new Map();
  let knowledge = null;
  let knowledgeError = null;
  const know = () => {
    if (knowledge || knowledgeError) return knowledge;
    try {
      knowledge = _internal.engineKnowledge();
    } catch (err) {
      // prawduct:allow prawduct/broad-except -- engine knowledge failing to load
      // must decline every content judgement (the safe answer), not fail the wrap.
      knowledgeError = err;
      log.info('TangleClaw ownership could not load engine knowledge; judging paths as usual', { error: err && err.message });
    }
    return knowledge;
  };

  for (const entry of dirty || []) {
    const p = entry.path;
    if (isStatePath(p)) {
      out.set(p, KINDS.STATE);
      continue;
    }
    if (entry.deleted || !root) continue;
    const k = know();
    if (!k) continue;

    let kindOf = null;
    let carrierRefusal = null;
    if (k.carriers.has(p)) {
      // #1619 — a managed block is not proof that a diff is safe maintenance.
      // The block is TangleClaw's to rewrite, but the carrier is the operator's
      // to commit, and the two came apart: generation used to write this
      // checkout's project name and this machine's origin into it, and this
      // branch staged that silently. PR #1618 landed one checkout's Medusa
      // routes on main exactly that way.
      //
      // The identity question is asked of the WORK copy ALONE, before and
      // independently of the head-vs-work comparison, because it is not a
      // question about the diff. Asking it only where the diff proved
      // block-only left a second route to the same outcome: every other exit
      // returns a bare `{kind: null}`, which falls through to the mtime rule
      // and is staged from `owned` — the bucket this guard exists to keep it
      // out of. Those exits are ordinary, not exotic: the operator edits their
      // own prose outside the block in the session the block acquired identity,
      // or a previously-ignored carrier is newly tracked so HEAD has no copy.
      //
      // Scoped to the BLOCK, not the file: the hand-maintained half is the
      // operator's and legitimately contains example URLs — this repo's own
      // global-rules mirror documents a MagicDNS link with a host and port.
      // Scanning the whole carrier would fire on every ordinary wrap, which the
      // fix brief forbids.
      const refuseIfIdentity = (work) => {
        const markers = k.markersFor(k.carriers.get(p));
        if (!markers || typeof work !== 'string') return null;

        const region = managedBlock.extractManagedBlock(work, markers);
        if (region === null) {
          // No region, and the two reasons are nothing alike.
          //
          // A file with a BEGIN or an END marker but no usable pair is a
          // MALFORMED TangleClaw region: the block cannot be read, so nothing
          // about its contents can be verified — and an unverifiable carrier
          // must be surfaced, not waved through. Reproduced by the Architect:
          // a BEGIN marker, a literal origin, no END, and the file was staged
          // as the session's own work. Nothing here rewrites it; the operator
          // decides, and the content is left exactly as it is.
          if (work.includes(markers.begin) || work.includes(markers.end)) {
            return {
              kind: null,
              identityRefusal: 'its TangleClaw block is malformed, so what it carries cannot be verified',
              reason: 'managed-block markers are malformed — the block cannot be read, so it is not provably safe to commit'
            };
          }

          // A LEGACY whole-file carrier has no markers by design: TangleClaw
          // generated the entire file before the managed-block era, and its
          // provenance is the generated header. Judge the whole file, because
          // the whole file is ours.
          if (_looksGenerated(work)) {
            const legacy = _carriesIdentity(work);
            if (!legacy) return null;
            return {
              kind: null,
              identityRefusal: `it is a generated carrier and carries ${legacy}`,
              reason: `generated carrier carries ${legacy} — regenerate it rather than commit this`
            };
          }

          // Otherwise it is an ordinary file that happens to share a carrier's
          // name, with no TangleClaw region at all. Not ours, and not our
          // business to refuse.
          return null;
        }

        const identity = _carriesIdentity(region);
        if (!identity) return null;
        return {
          kind: null,
          identityRefusal: `its TangleClaw block carries ${identity}`,
          reason: `managed block carries ${identity} — regenerate it rather than commit this`
        };
      };
      carrierRefusal = refuseIfIdentity;
      kindOf = (head, work) => {
        const markers = k.markersFor(k.carriers.get(p));
        if (!markers) return { kind: null, reason: `no managed-block comment form for '${k.carriers.get(p)}'` };
        const refusal = refuseIfIdentity(work);
        if (refusal) return refusal;
        const proof = managedBlock.differsOnlyInsideManagedBlock(head, work, markers);
        if (!proof.onlyInside) return { kind: null, reason: proof.reason };
        return { kind: KINDS.MAINTENANCE, reason: 'changed only inside TangleClaw\'s managed block' };
      };
    } else if ((k.hookSettingsPaths || []).includes(p)) {
      kindOf = (head, work) => judgeHookSettings(head, work, k.isTcHook);
    } else if (p === PROJECT_CONFIG_PATH) {
      kindOf = (head, work) => judgeProjectConfig(head, work, k.projectDefaults);
    }
    if (!kindOf) continue;

    let verdict;
    try {
      verdict = kindOf(_internal.gitShowHead(root, p), _internal.readWork(root, p));
    } catch (err) {
      // prawduct:allow prawduct/broad-except -- a file absent from HEAD or
      // unreadable on disk is "not provably TangleClaw's", which is the safe answer.
      verdict = { kind: null, reason: `could not read both copies (${err && err.message ? err.message.split('\n')[0] : 'unknown error'})` };
      // A carrier newly tracked this session has no HEAD copy, so the compare
      // above threw before anything looked at what the file actually contains.
      // Generation may well have classified it private and written an origin or
      // a token into it — which is precisely when it must not be staged.
      if (carrierRefusal) {
        try {
          const refusal = carrierRefusal(_internal.readWork(root, p));
          if (refusal) verdict = refusal;
        } catch {
          // Unreadable work copy: nothing more can be learned, and the bare
          // null verdict already stands.
        }
      }
    }
    if (verdict.kind) out.set(p, verdict.kind);
    else if (verdict.identityRefusal) identityRefusals.set(p, verdict.identityRefusal);
    // Logged on both answers: "why did the wrap ask about this file" must be
    // answerable from the log, and the causes look identical from outside.
    log.info(verdict.kind ? 'Path is TangleClaw maintenance' : 'Path is not provably TangleClaw\'s', { path: p, reason: verdict.reason });
  }
  // Carried on the map itself: only `judge` has read both copies, and the
  // ownership rules need the refusal to route the carrier to the operator
  // rather than letting it fall through to the mtime test (#1619).
  out.identityRefusals = identityRefusals;
  return out;
}

// Values a carrier the operator COMMITS must never contain (#1619). Each is a
// per-checkout or per-install fact, so its presence in shared bytes is the
// defect itself, not a symptom of one.
//
// A DETECTOR, deliberately not a fixer: what the block should say depends on
// the generator, and a wrap is the wrong place to regenerate. It reports and
// hands the decision to the operator through the existing "not provably ours"
// path — no new status, no new prompt, and silent on a normal wrap, because a
// block generated after #1619 matches none of these.
// Matched against the SHAPES generation emits, never against "a URL appears
// somewhere". Scoping to the managed block is not enough on its own: the
// Gemini/antigravity generator pushes the operator's global rules INSIDE the
// block it writes for AGENTS.md, and this install's rules document a MagicDNS
// link with a host and a port as an example. A bare origin pattern reads that
// example as a leak and fires on every ordinary wrap — the thing the fix brief
// forbids, and the same false positive I already had to fix once for the
// hand-maintained half of CLAUDE.md.
//
// A regex cannot tell an example from a live value in free prose, so it does not
// try: it matches the labelled line generation actually writes.
// Every line-anchored pattern below allows TangleClaw's own serialization
// wrappers before the content: the markdown carriers write a line bare, the
// codex generator indents it into a YAML block scalar, and the aider generator
// prefixes it with `# `. The SAME block, wrapped three ways — so an anchor that
// assumes bare markdown silently exempts two of the three carriers, which is
// how a private `.codex.yaml` force-added to the index kept its document paths
// while the guard stayed quiet.
const WRAP = '[#\\s]*';

const _IDENTITY_PATTERNS = [
  { what: 'a machine-specific API origin', re: /TangleClaw API base URL\*{0,2}:\s*`?https?:\/\/[A-Za-z0-9.-]+:\d+/ },
  { what: 'a name-scoped session route', re: /\/api\/sessions\/[^/\s<`]+\/medusa/ },
  { what: 'a live bearer token', re: /Authorization:\s*Bearer\s+(?!<)[A-Za-z0-9._-]{8,}/ },
  // The remaining three classes generation withholds from a committed carrier.
  // They arrive the same way the first three do — an older server regenerating
  // a carrier, or one migrating from private to shared — so the guard has to
  // recognise them even though current generation no longer emits them.
  // Each matches the shape the PRIVATE renderer writes, which is what such a
  // carrier actually holds.
  // Non-greedy for the name, for the same reason the embedded-body check is:
  // the renderer writes `- **${doc.name}**: `${path}``, so a document named
  // `a*b` defeats a no-asterisk class — and what escapes here is the
  // machine-specific path itself, which is the class this guard exists for.
  { what: 'a shared-document install path', re: new RegExp(`^${WRAP}- \\*\\*.+?\\*\\*:\\s*\`[~/][^\`]*\``, 'm') },
  { what: 'the project holding a shared-document lock', re: /LOCKED by [^(\n]+\(expires /i },
  { what: 'a per-machine file-existence check', re: /\(⚠️ file not found\)/ },
  // The renderer writes a machine path at THREE places, not one: the reference
  // line above, and these two fallbacks when an inline document is missing or
  // unreadable at generation time. Widening only the reference line left a
  // private carrier holding the operator's install path with the guard silent —
  // the sixth instance on this change of fixing the site shown rather than the
  // class. `test/identity-matrix.test.js` now fails if a fourth renderer
  // appears, so the next one cannot be found the same way.
  { what: 'a shared-document path in a read-failure notice', re: new RegExp(`^${WRAP}>\\s*⚠️\\s*(File not found|Failed to read):\\s*\``, 'm') }
];

// Inline shared-document bodies are the sixth class, and they have no literal
// of their own — the body is whatever the document says. What identifies them
// is the SHAPE the private renderer writes around them; see
// `_embedsSharedDocBody` for why the section heading alone is not enough.
const _SHARED_DOCS_HEADING = '## Shared Documents';

/**
 * Whether a block embeds a shared document's contents.
 *
 * @param {string} text
 * @returns {boolean}
 */
function _embedsSharedDocBody(text) {
  // The heading is wrapped too: `## Shared Documents` in markdown, and the
  // codex/aider generators strip the `#` markers, leaving `Shared Documents`.
  // Skip past whichever form was found, by ITS length.
  const heading = text.includes(_SHARED_DOCS_HEADING) ? _SHARED_DOCS_HEADING : 'Shared Documents';
  const start = text.indexOf(heading);
  if (start === -1) return false;
  const rest = text.slice(start + heading.length);
  // The markdown boundary only, and deliberately not widened to the wrapped
  // forms: `\n## ` cannot match `\n### `, which is what a GROUP heading is, so
  // widening it cuts the section before the body. For the codex and aider
  // serializations the scan therefore runs to end of file, which over-withholds
  // rather than under-, and no shipped guide contains a fence preceded by a
  // bold name for it to catch.
  const nextHeading = rest.search(/\n## /);
  const section = nextHeading === -1 ? rest : rest.slice(0, nextHeading);

  // Not "any fence in the section". `data/shared-docs-guide.md` IS a
  // `## Shared Documents` section, it ships fenced API examples, and it is
  // injected unconditionally — while the rendered doc list this looks for
  // exists only when the project HAS shared docs. Keying on the heading alone
  // therefore fired on every ordinary carrier of every project without any,
  // which is the common case and the counter-property the brief is strictest
  // about. It fired on this repo's own committed block.
  //
  // What the private renderer emits, and the guide never does, is a fence
  // directly beneath a bold DOCUMENT NAME line: `**<name>**`, optionally
  // followed by a lock warning, then the body. The guide's fences sit under
  // `###` headings and prose.
  // Same serialization tolerance as the patterns: strip TangleClaw's own
  // wrappers before reading a line's shape, or the codex and aider carriers —
  // which write this block indented and comment-prefixed — are exempt from the
  // check entirely.
  const unwrap = (line) => line.replace(/^[#\s]*/, '');
  const lines = section.split('\n');
  for (let i = 0; i < lines.length; i++) {
    if (!unwrap(lines[i]).startsWith('```')) continue;
    for (let back = i - 1; back >= 0 && i - back <= 3; back--) {
      const prev = unwrap(lines[back]).trim();
      if (!prev) continue;
      // Non-greedy rather than `[^*]+`: a document named `a*b` renders
      // `**a*b**`, which a no-asterisk class rejects — and the body under it
      // would then escape the check entirely.
      if (/^\*\*.+?\*\*/.test(prev)) return true;
      break; // the nearest non-empty line is not a document name
    }
  }
  return false;
}

// TangleClaw's own provenance on a whole-file carrier, from the era before
// managed blocks. `lib/engines.js` writes it into the first lines and reads it
// back the same way to decide whether a whole-file config is safe to replace.
const GENERATED_HEADER_MARK = 'Generated by TangleClaw';

/**
 * Whether a carrier with no managed-block region is one TangleClaw generated
 * whole, rather than an ordinary file that shares a carrier's name.
 *
 * @param {string} text
 * @returns {boolean}
 */
function _looksGenerated(text) {
  return text.split('\n').slice(0, 3).some((line) => line.includes(GENERATED_HEADER_MARK));
}

/**
 * The first identity-shaped value a carrier's text contains, or null.
 *
 * @param {string} text - The carrier's work-tree content.
 * @returns {string|null} A human phrase naming what was found.
 */
function _carriesIdentity(text) {
  if (typeof text !== 'string' || !text) return null;
  for (const { what, re } of _IDENTITY_PATTERNS) {
    if (re.test(text)) return what;
  }
  if (_embedsSharedDocBody(text)) return 'an embedded shared-document body';
  return null;
}

