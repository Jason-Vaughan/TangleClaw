'use strict';

/*
 * #858 — an engine switch leaves the previous engine's config file behind as
 * stale canon. `generateConfig` writes only the active engine's file, so the
 * old one stayed on disk unmarked, read by convention (`CLAUDE.md`), and
 * steadily wrong. These drive the real switch path (`projects.updateProject`)
 * and read the files back: the retired file says it is inactive and names the
 * live engine; a hand-written or plugin-owned file is left alone with the
 * reason; switching back regenerates without a false drift warning.
 */

const { describe, it, before, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { setLevel, setConsoleStream } = require('../lib/logger');
setLevel('error');
const store = require('../lib/store');
const projects = require('../lib/projects');
const engines = require('../lib/engines');

describe('#858 an engine switch retires the previous engine\'s config file', () => {
  let tmpDir;
  let projectsDir;

  before(() => {
    tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'tc-switch-retire-'));
    projectsDir = path.join(tmpDir, 'projects');
    fs.mkdirSync(projectsDir, { recursive: true });
    store._setBasePath(path.join(tmpDir, 'tangleclaw'));
    store.init();
    const config = store.config.load();
    config.projectsDir = projectsDir;
    store.config.save(config);
  });

  after(() => {
    store.close();
    fs.rmSync(tmpDir, { recursive: true, force: true });
  });

  /**
   * Create a project on an engine with its config written, the way a project
   * looks before a switch.
   * @param {string} name - Project name.
   * @param {string} engine - Engine id.
   * @returns {string} The project directory.
   */
  function seed(name, engine) {
    const dir = path.join(projectsDir, name);
    const created = projects.createProject({ name, engine });
    assert.deepEqual(created.errors || [], [], `seed ${name}`);
    const projConfig = store.projectConfig.load(dir);
    projConfig.engine = engine;
    store.projectConfig.save(dir, projConfig);
    engines.writeEngineConfig(engine, dir, projConfig, store.engines.get(engine));
    return dir;
  }

  it('claude → antigravity: the generated CLAUDE.md becomes an inactive notice naming the live engine and file', async () => {
    const dir = seed('retire-claude', 'claude');
    assert.match(fs.readFileSync(path.join(dir, 'CLAUDE.md'), 'utf8'), /^# CLAUDE\.md — Generated by TangleClaw/);

    const result = await projects.updateProject('retire-claude', { engine: 'antigravity' });
    assert.deepEqual(result.errors || [], []);

    const claudeMd = fs.readFileSync(path.join(dir, 'CLAUDE.md'), 'utf8');
    assert.match(claudeMd, /TangleClaw: INACTIVE engine config/);
    assert.match(claudeMd, /switched from claude to antigravity/);
    assert.match(claudeMd, /The live config is AGENTS\.md/);
    assert.doesNotMatch(claudeMd, /Generated by TangleClaw/, 'nothing left that reads as a live generated config');
    assert.match(fs.readFileSync(path.join(dir, 'AGENTS.md'), 'utf8'), /BEGIN:tangleclaw/, 'the live engine\'s file was written');
  });

  it('antigravity → claude: only the managed block becomes the notice; the operator\'s content outside it stays', async () => {
    const dir = seed('retire-agy', 'antigravity');
    const agents = path.join(dir, 'AGENTS.md');
    fs.writeFileSync(agents, `# My own notes\n\nKeep me.\n\n${fs.readFileSync(agents, 'utf8')}`);

    const result = await projects.updateProject('retire-agy', { engine: 'claude' });
    assert.deepEqual(result.errors || [], []);

    const after = fs.readFileSync(agents, 'utf8');
    assert.match(after, /^# My own notes\n\nKeep me\./, 'content outside the markers is the operator\'s');
    assert.match(after, /BEGIN:tangleclaw[\s\S]*INACTIVE engine config[\s\S]*switched from antigravity to claude[\s\S]*END:tangleclaw/);
    assert.match(fs.readFileSync(path.join(dir, 'CLAUDE.md'), 'utf8'), /^# CLAUDE\.md — Generated by TangleClaw/);
  });

  it('switching back regenerates over the notice without calling it operator drift', async () => {
    const dir = seed('retire-roundtrip', 'claude');
    await projects.updateProject('retire-roundtrip', { engine: 'antigravity' });
    assert.match(fs.readFileSync(path.join(dir, 'CLAUDE.md'), 'utf8'), /INACTIVE engine config/);

    const lines = [];
    setConsoleStream({ write: (s) => lines.push(String(s)) });
    setLevel('warn');
    try {
      await projects.updateProject('retire-roundtrip', { engine: 'claude' });
    } finally {
      setConsoleStream(null);
      setLevel('error');
    }
    const claudeMd = fs.readFileSync(path.join(dir, 'CLAUDE.md'), 'utf8');
    assert.match(claudeMd, /^# CLAUDE\.md — Generated by TangleClaw/, 'live again');
    assert.doesNotMatch(claudeMd, /INACTIVE engine config/);
    assert.deepEqual(lines.filter((l) => /drift detected/.test(l)), [],
      'the notice is TangleClaw\'s own content — overwriting it is not overwriting hand-edits');
    // And the file the project just left is now the retired one.
    assert.match(fs.readFileSync(path.join(dir, 'AGENTS.md'), 'utf8'), /INACTIVE engine config[\s\S]*switched from antigravity to claude/);
  });

  it('switching back onto a managed-block engine regenerates over the notice without a false drift warning', async () => {
    // The mirror of the whole-file round trip: the managed-block drift
    // exemption (`priorIsNotice`) is what keeps AGENTS.md's regeneration
    // from logging "overwriting hand-edits" about TangleClaw's own notice.
    const dir = seed('retire-roundtrip-agy', 'antigravity');
    await projects.updateProject('retire-roundtrip-agy', { engine: 'claude' });
    assert.match(fs.readFileSync(path.join(dir, 'AGENTS.md'), 'utf8'), /INACTIVE engine config/);

    const lines = [];
    setConsoleStream({ write: (s) => lines.push(String(s)) });
    setLevel('warn');
    try {
      await projects.updateProject('retire-roundtrip-agy', { engine: 'antigravity' });
    } finally {
      setConsoleStream(null);
      setLevel('error');
    }
    const agents = fs.readFileSync(path.join(dir, 'AGENTS.md'), 'utf8');
    assert.match(agents, /BEGIN:tangleclaw/, 'live again');
    assert.doesNotMatch(agents, /INACTIVE engine config/);
    assert.deepEqual(lines.filter((l) => /drift detected/.test(l)), [],
      'the notice inside the markers is TangleClaw\'s own content');
    assert.match(fs.readFileSync(path.join(dir, 'CLAUDE.md'), 'utf8'), /INACTIVE engine config[\s\S]*switched from claude to antigravity/);
  });

  it('a carrier with one unmatched marker is refused, never whole-file replaced (#1132)', () => {
    // The ownership question used to be "does the file have BOTH markers", and
    // a carrier with one said no. Control then fell past the managed-block
    // branch: a file whose generated header is present got its WHOLE contents
    // replaced by the inactive notice — destroying the operator's sections and
    // the other tool's block, the exact loss the managed block exists to
    // prevent — and one without that header took a skip whose stated reason
    // ("no managed markers") was untrue of the file, leaving a superseded
    // config live as canon. Mutation this catches: restoring the both-markers
    // gate, which turns this into a silent whole-file write.
    const dir = seed('retire-unmatched-marker', 'antigravity');
    const agents = path.join(dir, 'AGENTS.md');
    const markers = engines._managedBlockMarkers('markdown');
    const seeded =
      '# AGENTS\n\n**CRITICAL RULE:** operator content that must survive.\n\n'
      + '<!-- BEGIN:nextjs-agent-rules -->\nvendor\n<!-- END:nextjs-agent-rules -->\n\n'
      + `${markers.begin}\ntruncated — no end marker\n`;
    fs.writeFileSync(agents, seeded);

    const result = engines.retireInactiveEngineConfig(dir, 'antigravity', 'claude');
    assert.equal(result.retired, false, 'an unreadable marker set is not a retirement');
    assert.equal(result.reason, 'managed-block merge refused');
    assert.match(result.error, /malformed/);
    assert.equal(fs.readFileSync(agents, 'utf8'), seeded,
      'the co-owned file is byte-identical — no whole-file notice, no partial splice');
  });

  it('a misordered pair on the retired carrier is repaired, and the switch says so (#1132)', () => {
    const dir = seed('retire-misordered', 'antigravity');
    const agents = path.join(dir, 'AGENTS.md');
    const markers = engines._managedBlockMarkers('markdown');
    fs.writeFileSync(
      agents,
      `# AGENTS\n\n**CRITICAL RULE:** keep me.\n\n${markers.end}\nstranded\n${markers.begin}\n`
    );

    const result = engines.retireInactiveEngineConfig(dir, 'antigravity', 'claude');
    assert.equal(result.retired, true);
    const after = fs.readFileSync(agents, 'utf8');
    assert.ok(after.includes('**CRITICAL RULE:** keep me.'), 'operator content outside the block survives');
    assert.ok(after.includes('stranded'), 'text between the misordered markers survives');
    assert.ok(after.includes('INACTIVE engine config'), 'the notice landed inside the repaired block');
    assert.equal(after.split(markers.begin).length - 1, 1);
    assert.equal(after.split(markers.end).length - 1, 1);
  });

  it('a failed retirement is an error the switch logs at warn — not a choice logged as "left alone"', async () => {
    const dir = seed('retire-unwritable', 'antigravity');
    const agents = path.join(dir, 'AGENTS.md');
    // Only the file the retire path writes is read-only; the new engine's
    // config still lands, so the failure measured is the retirement's own.
    fs.chmodSync(agents, 0o444);
    const lines = [];
    setConsoleStream({ write: (s) => lines.push(String(s)) });
    setLevel('warn');
    let r;
    try {
      r = engines.retireInactiveEngineConfig(dir, 'antigravity', 'claude');
      await projects.updateProject('retire-unwritable', { engine: 'claude' });
    } finally {
      setConsoleStream(null);
      setLevel('error');
      fs.chmodSync(agents, 0o644);
    }
    assert.equal(r.retired, false);
    assert.equal(r.reason, 'could not write it');
    assert.ok(r.error, 'a failure carries its error, a skip does not');
    assert.ok(lines.some((l) => /WARN/.test(l) && /Failed to retire the previous engine config/.test(l)),
      `the switch warns:\n${lines.join('')}`);
  });

  it('when the new engine\'s config cannot be written, the previous one stays live and the switch says so at warn', async () => {
    // A notice would name a live file that does not exist. The gate in
    // updateProject skips retirement on a failed write; `if (false)` in its
    // place writes the notice anyway and this goes red.
    const dir = seed('retire-write-fails', 'antigravity');
    const agents = path.join(dir, 'AGENTS.md');
    fs.chmodSync(dir, 0o555);
    const lines = [];
    setConsoleStream({ write: (s) => lines.push(String(s)) });
    setLevel('warn');
    try {
      await projects.updateProject('retire-write-fails', { engine: 'claude' });
    } finally {
      setConsoleStream(null);
      setLevel('error');
      fs.chmodSync(dir, 0o755);
    }
    const after = fs.readFileSync(agents, 'utf8');
    assert.doesNotMatch(after, /INACTIVE engine config/, 'the previous config is still the only one that exists — it stays live');
    assert.match(after, /BEGIN:tangleclaw/);
    assert.equal(fs.existsSync(path.join(dir, 'CLAUDE.md')), false, 'precondition: the new config was not written');
    assert.ok(lines.some((l) => /WARN/.test(l) && /Previous engine config left in place — the new engine config was not written/.test(l)),
      `the switch says so:\n${lines.join('')}`);
  });

  it('a plugin-governed CLAUDE.md is never touched — the file is the plugin\'s', async () => {
    const dir = seed('retire-governed', 'claude');
    fs.mkdirSync(path.join(dir, '.claude'), { recursive: true });
    fs.writeFileSync(path.join(dir, '.claude', 'settings.json'), JSON.stringify({ enabledPlugins: { 'prawduct@prawduct': true } }));
    const before = '# Plugin-owned anchor\n\nHands off.\n';
    fs.writeFileSync(path.join(dir, 'CLAUDE.md'), before);

    const r = engines.retireInactiveEngineConfig(dir, 'claude', 'codex');
    assert.equal(r.retired, false);
    assert.match(r.reason, /plugin-governed/);
    assert.equal(fs.readFileSync(path.join(dir, 'CLAUDE.md'), 'utf8'), before);
  });

  it('a hand-written file with no generated header and no markers is left alone, and says why', () => {
    const dir = path.join(projectsDir, 'retire-handwritten');
    fs.mkdirSync(dir, { recursive: true });
    const before = '# Hand-written CLAUDE.md\n\nMine.\n';
    fs.writeFileSync(path.join(dir, 'CLAUDE.md'), before);

    const r = engines.retireInactiveEngineConfig(dir, 'claude', 'codex');
    assert.equal(r.retired, false);
    assert.match(r.reason, /not TangleClaw-written/);
    assert.equal(fs.readFileSync(path.join(dir, 'CLAUDE.md'), 'utf8'), before);
  });

  it('an engine with no config file, a missing file, and an already-retired file each report their reason', () => {
    const dir = path.join(projectsDir, 'retire-reasons');
    fs.mkdirSync(dir, { recursive: true });
    assert.match(engines.retireInactiveEngineConfig(dir, 'openclaw', 'claude').reason, /has no config file/);
    assert.match(engines.retireInactiveEngineConfig(dir, 'claude', 'codex').reason, /no config file on disk/);
    fs.writeFileSync(path.join(dir, 'CLAUDE.md'), '# CLAUDE.md — Generated by TangleClaw\n\nlive\n');
    assert.equal(engines.retireInactiveEngineConfig(dir, 'claude', 'codex').retired, true);
    assert.match(engines.retireInactiveEngineConfig(dir, 'claude', 'codex').reason, /already marked inactive/);
  });

  it('every whole-file generator writes the header the retire path detects', () => {
    // One constant binds the producers and the detector (Critic R-4): a
    // header edit that dropped the mark would make retirement call a
    // TangleClaw-written file hand-written.
    const dir = path.join(projectsDir, 'retire-headers');
    fs.mkdirSync(dir, { recursive: true });
    for (const engine of ['claude', 'codex', 'aider']) {
      const profile = store.engines.get(engine);
      const content = engines.generateConfig(engine, { engine, rules: {} }, dir);
      assert.ok(content.split('\n').slice(0, 3).some((l) => l.includes(engines.GENERATED_HEADER_MARK)),
        `${engine}'s generated header carries GENERATED_HEADER_MARK (${profile.configFormat.filename})`);
    }
  });

  describe('_atomicWriteConfigFile: temp-file + rename, read-only refused up front (#1291)', () => {
    /**
     * A throwaway directory outside the project fixtures above, so a chmod
     * here can never collide with another test's own permission dance.
     * @returns {string}
     */
    function tmp() {
      return fs.mkdtempSync(path.join(os.tmpdir(), 'tc-atomic-write-'));
    }

    it('writes a brand-new target with no prior file to preserve a mode from', () => {
      const dir = tmp();
      const target = path.join(dir, 'AGENTS.md');
      engines._atomicWriteConfigFile(target, 'brand new\n');
      assert.equal(fs.readFileSync(target, 'utf8'), 'brand new\n');
      assert.deepEqual(fs.readdirSync(dir), ['AGENTS.md'], 'no dangling temp file');
      fs.rmSync(dir, { recursive: true, force: true });
    });

    it('overwrites an existing target via rename, preserving its mode', () => {
      const dir = tmp();
      const target = path.join(dir, 'AGENTS.md');
      fs.writeFileSync(target, 'old\n', { mode: 0o640 });
      engines._atomicWriteConfigFile(target, 'new\n');
      assert.equal(fs.readFileSync(target, 'utf8'), 'new\n');
      assert.equal(fs.statSync(target).mode & 0o777, 0o640, 'the pre-existing mode survives the rename');
      assert.deepEqual(fs.readdirSync(dir), ['AGENTS.md'], 'no dangling temp file');
      fs.rmSync(dir, { recursive: true, force: true });
    });

    it('refuses a chmod 0o444 target with EACCES before any temp file is created', () => {
      const dir = tmp();
      const target = path.join(dir, 'AGENTS.md');
      fs.writeFileSync(target, 'protected\n');
      fs.chmodSync(target, 0o444);
      try {
        assert.throws(() => engines._atomicWriteConfigFile(target, 'new\n'), (err) => err.code === 'EACCES');
      } finally {
        fs.chmodSync(target, 0o644);
      }
      assert.equal(fs.readFileSync(target, 'utf8'), 'protected\n', 'the read-only target is byte-identical');
      assert.deepEqual(fs.readdirSync(dir), ['AGENTS.md'], 'no temp file was created before the refusal');
      fs.rmSync(dir, { recursive: true, force: true });
    });

    it('a mid-write failure (ENOSPC-shaped: temp-file creation itself fails) leaves the target byte-identical and no dangling temp file', () => {
      const dir = tmp();
      const target = path.join(dir, 'AGENTS.md');
      fs.writeFileSync(target, 'original content\n');
      // The target file itself stays writable; only the DIRECTORY loses its
      // write bit, so creating the sibling temp file fails exactly the way a
      // disk-full write would — after the read-only-target check passes, before
      // any bytes of the new content reach disk.
      fs.chmodSync(dir, 0o555);
      try {
        assert.throws(() => engines._atomicWriteConfigFile(target, 'new content\n'));
      } finally {
        fs.chmodSync(dir, 0o755);
      }
      assert.equal(fs.readFileSync(target, 'utf8'), 'original content\n',
        'a crash mid-write leaves the carrier wholly old, never truncated');
      assert.deepEqual(fs.readdirSync(dir), ['AGENTS.md'], 'no dangling temp file left behind');
      fs.rmSync(dir, { recursive: true, force: true });
    });
  });

  it('a mid-write failure during retirement leaves the existing co-owned carrier byte-identical (#1291)', () => {
    const dir = seed('retire-midwrite-fail', 'antigravity');
    const agents = path.join(dir, 'AGENTS.md');
    const before = fs.readFileSync(agents, 'utf8');
    // AGENTS.md itself stays writable; the directory loses its write bit, so
    // the sibling temp file the atomic write needs can never be created —
    // the same failure shape a disk-full write produces, exercised through
    // the real retire path rather than the helper directly.
    fs.chmodSync(dir, 0o555);
    let r;
    try {
      r = engines.retireInactiveEngineConfig(dir, 'antigravity', 'claude');
    } finally {
      fs.chmodSync(dir, 0o755);
    }
    assert.equal(r.retired, false);
    assert.ok(r.error, 'a mid-write failure is a reported failure, not a silent skip');
    assert.equal(fs.readFileSync(agents, 'utf8'), before,
      'the co-owned carrier is untouched — no truncation, no partial write');
    assert.deepEqual(fs.readdirSync(dir).filter((f) => f.includes('.tmp-')), [],
      'no dangling temp file left behind');
  });

  describe('syncEngineHooks accepts a projConfigOverride to skip a redundant project-config read (#2232)', () => {
    /**
     * An unregistered, store-unaware project directory: `getByPath` resolves
     * null here, which is the only case `projConfig` (override or loaded) is
     * actually consulted for the engine id.
     * @returns {string}
     */
    function unregisteredProjectDir() {
      const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'tc-sync-hooks-override-'));
      fs.mkdirSync(path.join(dir, '.claude'), { recursive: true });
      return dir;
    }

    it('consults the override instead of calling store.projectConfig.load again', () => {
      const dir = unregisteredProjectDir();
      const originalLoad = store.projectConfig.load;
      let loadCalls = 0;
      store.projectConfig.load = (...args) => { loadCalls += 1; return originalLoad(...args); };
      try {
        engines.syncEngineHooks(dir, undefined, { engine: 'codex' });
      } finally {
        store.projectConfig.load = originalLoad;
      }
      assert.equal(loadCalls, 0, 'a caller that already loaded the config must not trigger a second, redundant read');
      fs.rmSync(dir, { recursive: true, force: true });
    });

    it('omitting the override preserves the existing store.projectConfig.load fallback', () => {
      const dir = unregisteredProjectDir();
      const originalLoad = store.projectConfig.load;
      let loadCalls = 0;
      store.projectConfig.load = (...args) => { loadCalls += 1; return originalLoad(...args); };
      try {
        engines.syncEngineHooks(dir);
      } finally {
        store.projectConfig.load = originalLoad;
      }
      assert.equal(loadCalls, 1, 'omitting projConfigOverride must still read the project config from disk as before');
      fs.rmSync(dir, { recursive: true, force: true });
    });
  });
});
